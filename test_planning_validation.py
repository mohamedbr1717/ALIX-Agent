"""Decision 1 — planner-draft validation (spec §4.6 / §7).

Planner output is untrusted input: an unknown tool, an
out-of-schema argument key, a forged id/state key, or a size
violation rejects the WHOLE draft and stores NOTHING. Identifiers
and timestamps are always generated by code, never the model.
"""
import tempfile
import unittest
from datetime import datetime, timedelta, timezone
from pathlib import Path

from domain.planning.states import BlockedReason, StepState
from domain.planning.validation import (
    PlanRejected,
    validate_plan_draft,
)

from features.planning.application.dto.planning import (
    CreatePlanRequest,
)
from features.planning.application.ports.planner import PlannerPort
from features.planning.application.use_cases.create_plan import (
    CreatePlanUseCase,
)
from features.planning.infrastructure.adapters.json_plan_store import (
    JsonPlanStore,
)

NOW = datetime(2026, 10, 27, 12, 0, tzinfo=timezone.utc)

ALLOWLIST = frozenset({"read_file", "list_files", "calendar_delete"})
SCHEMAS = {
    "read_file": frozenset({"path"}),
    "list_files": frozenset({"path"}),
    "calendar_delete": frozenset({"event_id"}),
}


def fixed_clock():
    return NOW


class ScriptedPlanner(PlannerPort):
    def __init__(self, draft=None, exc=None):
        self._draft = draft
        self._exc = exc
        self.plan_calls = 0

    def plan(self, goal, prior_actions, context):
        self.plan_calls += 1
        if self._exc is not None:
            raise self._exc
        return self._draft

    def decompose(self, goal, failed_step, remaining_steps):
        return {"mode": "give_up"}


def step(intent="خطوة", tool="read_file", args=None, **extra):
    base = {"intent": intent, "tool": tool, "args": args or {"path": "x"}}
    base.update(extra)
    return base


class ValidationCase(unittest.TestCase):
    def validate(self, draft):
        return validate_plan_draft(draft, ALLOWLIST, SCHEMAS)

    def test_valid_draft_accepted(self):
        result = self.validate({"steps": [step(), step("ب", "list_files", {})]})
        self.assertNotIsInstance(result, PlanRejected)
        self.assertEqual(len(result), 2)

    def test_unknown_tool_rejects_whole_draft(self):
        result = self.validate(
            {"steps": [step(), step(tool="delete_everything")]}
        )
        self.assertIsInstance(result, PlanRejected)
        self.assertEqual(result.reason, "tool_not_in_allowlist")

    def test_args_outside_schema_rejected(self):
        result = self.validate(
            {"steps": [step(args={"path": "x", "shell": "rm"})]}
        )
        self.assertIsInstance(result, PlanRejected)
        self.assertEqual(result.reason, "args_outside_schema")

    def test_extra_step_key_rejected(self):
        result = self.validate(
            {"steps": [step(state="succeeded")]}
        )
        self.assertIsInstance(result, PlanRejected)
        self.assertEqual(result.reason, "step_keys_mismatch")

    def test_forged_ids_rejected(self):
        for forged in ("step_id", "idempotency_key", "plan_id"):
            with self.subTest(forged=forged):
                result = self.validate(
                    {"steps": [step(**{forged: "pwn"})]}
                )
                self.assertIsInstance(result, PlanRejected)
                self.assertEqual(
                    result.reason, "step_keys_mismatch"
                )

    def test_zero_steps_rejected(self):
        result = self.validate({"steps": []})
        self.assertIsInstance(result, PlanRejected)
        self.assertEqual(result.reason, "no_steps")

    def test_thirteen_steps_rejected_twelve_accepted(self):
        result = self.validate({"steps": [step() for _ in range(13)]})
        self.assertIsInstance(result, PlanRejected)
        self.assertEqual(result.reason, "too_many_steps")
        result = self.validate({"steps": [step() for _ in range(12)]})
        self.assertNotIsInstance(result, PlanRejected)

    def test_malformed_drafts_rejected(self):
        for bad in (
            None,
            [],
            "steps",
            {"steps": {}},
            {"steps": [step()], "extra": 1},
            {"steps": [{"intent": "x", "tool": "read_file"}]},
            {"steps": [step(intent="  ")]},
            {"steps": [step(args="not-a-dict")]},
        ):
            with self.subTest(bad=repr(bad)[:40]):
                self.assertIsInstance(
                    self.validate(bad), PlanRejected
                )


class CreatePlanCase(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.store = JsonPlanStore(
            Path(self._tmp.name) / "plans.json"
        )

    def build(self, planner):
        return CreatePlanUseCase(
            planner=planner,
            store=self.store,
            allowlist=ALLOWLIST,
            tool_schemas=SCHEMAS,
            destructive_tools=frozenset({"calendar_delete"}),
            confirming_tools=frozenset({"calendar_delete"}),
            clock=fixed_clock,
        )

    def test_rejected_draft_stores_nothing(self):
        use_case = self.build(
            ScriptedPlanner({"steps": [step(tool="nope")]})
        )
        outcome = use_case.execute(
            CreatePlanRequest(goal="هدف", origin="interactive")
        )
        self.assertFalse(outcome.created)
        self.assertEqual(outcome.reason, "tool_not_in_allowlist")
        self.assertEqual(self.store.list_all(), [])

    def test_planner_exception_stores_nothing(self):
        use_case = self.build(
            ScriptedPlanner(exc=RuntimeError("LLM down"))
        )
        outcome = use_case.execute(
            CreatePlanRequest(goal="هدف", origin="interactive")
        )
        self.assertFalse(outcome.created)
        self.assertEqual(outcome.reason, "planner_error")
        self.assertEqual(self.store.list_all(), [])

    def test_code_generates_all_identifiers(self):
        draft = {
            "steps": [
                step("أولى"),
                step("ثانية", "list_files", {}),
            ]
        }
        use_case = self.build(ScriptedPlanner(draft))
        outcome = use_case.execute(
            CreatePlanRequest(goal="هدف", origin="interactive")
        )
        self.assertTrue(outcome.created)
        plan = outcome.plan
        self.assertTrue(plan.plan_id.startswith("p_20261027T120000_"))
        self.assertEqual(
            [s.step_id for s in plan.steps], ["s1", "s2"]
        )
        for s in plan.steps:
            self.assertEqual(
                s.idempotency_key, f"{plan.plan_id}:{s.step_id}"
            )
            self.assertEqual(s.state, StepState.PENDING)
            self.assertEqual(s.created_at, plan.created_at)
        created = datetime.fromisoformat(plan.created_at)
        expires = datetime.fromisoformat(plan.expires_at)
        self.assertEqual(expires - created, timedelta(hours=24))
        # Persisted.
        self.assertIsNotNone(self.store.get(plan.plan_id))

    def test_below_min_steps_rejected(self):
        use_case = self.build(ScriptedPlanner({"steps": [step()]}))
        outcome = use_case.execute(
            CreatePlanRequest(
                goal="هدف", origin="interactive", min_steps=2
            )
        )
        self.assertFalse(outcome.created)
        self.assertEqual(outcome.reason, "below_min_steps")
        self.assertEqual(self.store.list_all(), [])

    def test_prior_actions_recorded_with_hash_and_summary(self):
        use_case = self.build(
            ScriptedPlanner({"steps": [step(), step("ب", "list_files", {})]})
        )
        outcome = use_case.execute(
            CreatePlanRequest(
                goal="هدف",
                origin="interactive",
                prior_actions=(
                    ("list_files", {"path": "w"}, "3 ملفات"),
                ),
            )
        )
        self.assertTrue(outcome.created)
        prior = outcome.plan.prior_actions
        self.assertEqual(len(prior), 1)
        self.assertEqual(prior[0].tool, "list_files")
        self.assertEqual(len(prior[0].args_hash), 64)
        self.assertEqual(prior[0].result_ref, "3 ملفات")

    def test_result_refs_are_redacted_and_truncated(self):
        secretish = "token = sk-abcdef1234567890 " + "x" * 600
        use_case = self.build(
            ScriptedPlanner({"steps": [step(), step("ب", "list_files", {})]})
        )
        outcome = use_case.execute(
            CreatePlanRequest(
                goal="هدف",
                origin="interactive",
                prior_actions=(("read_file", {}, secretish),),
            )
        )
        ref = outcome.plan.prior_actions[0].result_ref
        self.assertNotIn("sk-abcdef", ref)
        self.assertLessEqual(len(ref), 500)


if __name__ == "__main__":
    unittest.main()
